CREATE TABLE IF NOT EXISTS orden_reabastecimiento (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_catalogo          BIGINT        NOT NULL REFERENCES catalogo (id),
    id_sucursal          BIGINT        NOT NULL REFERENCES sucursal (id_sucursal),
    id_proveedor         BIGINT        REFERENCES proveedores (id),
    stock_al_generar     NUMERIC(10,2) NOT NULL,
    stock_minimo         NUMERIC(10,2) NOT NULL,
    stock_maximo         NUMERIC(10,2),
    precio_referencia    NUMERIC(12,2),
    cantidad_sugerida    NUMERIC(10,2) NOT NULL CHECK (cantidad_sugerida > 0),
    cantidad_aprobada    NUMERIC(10,2) CHECK (cantidad_aprobada IS NULL OR cantidad_aprobada > 0),
    estado               VARCHAR(20)   NOT NULL CHECK (estado IN ('PENDIENTE', 'APROBADA', 'RECHAZADA', 'CONVERTIDA', 'VENCIDA')),
    motivo_rechazo       VARCHAR(255),
    id_compra            BIGINT,
    fecha_atencion       TIMESTAMP(6),
    usuario_creacion     VARCHAR(50),
    usuario_modificacion VARCHAR(50),
    fecha_generacion     TIMESTAMP(6),
    fecha_actualizacion  TIMESTAMP(6)
);

CREATE INDEX IF NOT EXISTS idx_orden_reab_sucursal ON orden_reabastecimiento (id_sucursal);
CREATE INDEX IF NOT EXISTS idx_orden_reab_catalogo ON orden_reabastecimiento (id_catalogo);
CREATE INDEX IF NOT EXISTS idx_orden_reab_estado ON orden_reabastecimiento (estado);

CREATE UNIQUE INDEX IF NOT EXISTS ux_orden_reab_abierta
    ON orden_reabastecimiento (id_catalogo, id_sucursal)
    WHERE estado IN ('PENDIENTE', 'APROBADA');

CREATE INDEX IF NOT EXISTS idx_kardex_ultimo_mov
    ON kardex (id_catalogo, id_sucursal, fecha DESC, id_articulo_kardex DESC);

CREATE INDEX IF NOT EXISTS idx_producto_fefo
    ON productos (id_catalogo, id_sucursal, fecha_venc);

